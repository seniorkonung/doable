import '../../../tag/domain/tag.dart';
import '../../../tag/domain/tag_id.dart';

/// Узкий контракт набора тегов черновика для панели тегов.
///
/// Связан с одной сессией создания: предоставляет только наблюдаемый набор
/// идентификаторов, явное локальное включение и исключение. Изменения меняют
/// только черновик и не записывают назначений; команды графа, ревизии и
/// детали хранилища в контракт не входят. Во время отправки и после закрытия
/// сессии включение и исключение набор не меняют.
abstract interface class IntentionDraftTagSet {
  /// Неизменяемый набор идентификаторов в порядке включения.
  Set<TagId> get current;

  /// Изменения набора идентификаторов. Поток завершается при закрытии
  /// сессии.
  Stream<Set<TagId>> get changes;

  /// Явно включает подтверждённый [tag]; его название сохраняется как
  /// последнее известное для показа. Повторное включение ничего не меняет.
  void add(Tag tag);

  /// Явно исключает тег [tagId] из набора вместе с его показом в выбранных
  /// тегах. Исключение тега вне набора ничего не меняет.
  void remove(TagId tagId);
}
