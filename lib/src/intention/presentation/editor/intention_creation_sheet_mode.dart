/// Режим размера панели создания намерения.
///
/// Принадлежит экранной сессии, но не черновику: смена режима не делает
/// черновик изменённым, не отправляет сохранение и не запрашивает закрытие.
enum IntentionCreationSheetMode {
  /// Высота по содержимому в пределах доступной области с видимым участком
  /// страницы над панелью. Каждое новое открытие начинается в этом режиме.
  compact,

  /// Вся доступная высота экрана над клавиатурой и под строкой состояния.
  expanded,
}
